    private fun trait(
        id: String,
        category: TraitCategory,
        effect: TraitEffect,
        visibility: TraitVisibility = TraitVisibility.VISIBLE,
        seasonId: String? = null,
        activation: TraitActivationConditions = TraitActivationConditions(),
        dependencies: Set<String> = emptySet(),
        conflicts: Set<String> = emptySet(),
        catalogId: String = "core",
        packageFolder: String? = null
    ) = TraitDefinition(
        id = id,
        titleKey = "trait.$id.title",
        descriptionKey = "trait.$id.description",
        category = category,
        visibility = visibility,
        activation = activation,
        dependencies = dependencies,
        conflicts = conflicts,
        effects = setOf(effect),
        seasonId = seasonId,
        catalogId = catalogId,
        packageFolder = packageFolder ?: id.split('_').joinToString("") { part -> part.replaceFirstChar { it.uppercase() } } + "Trait"
    )
